function formatMessage(message: string, values?: Record<string, string | number>) {
  if (!values) return message;

  return Object.entries(values).reduce(
    (nextMessage, [key, value]) => nextMessage.replaceAll(`{${key}}`, String(value)),
    message
  );
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("en");

  useEffect(() => {
    const savedLocale = localStorage.getItem("locale");
    if (savedLocale === "ar" || savedLocale === "en") {
      setLocaleState(savedLocale);
    }
  }, []);

  const direction = locale === "ar" ? "rtl" : "ltr";

  useEffect(() => {
    document.documentElement.lang = locale;
    document.documentElement.dir = direction;
  }, [direction, locale]);

  const value = useMemo<I18nContextValue>(() => {
    function setLocale(nextLocale: Locale) {
      setLocaleState(nextLocale);
      localStorage.setItem("locale", nextLocale);
    }

    function toggleLocale() {
      setLocale(locale === "ar" ? "en" : "ar");
    }

    function t(key: TranslationKey, values?: Record<string, string | number>) {
      return formatMessage(translations[locale][key] ?? translations.en[key], values);
    }

    return {
      locale,
      direction,
      setLocale,
      toggleLocale,
      t,
    };
  }, [direction, locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);

  if (!context) {
    throw new Error("useI18n must be used inside I18nProvider");
  }

  return context;
}

export function getLocaleLabel(locale: Locale) {
  return localeLabels[locale];
}

export function translateCommonLabel(
  t: I18nContextValue["t"],
  label: string | undefined
) {
  if (!label) return label;

  const key = commonLabelKeys[label];
  return key ? t(key) : label;
}
